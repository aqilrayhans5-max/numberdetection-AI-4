"""DigitLab: browser-drawn, exactly-three-digit handwritten recognition.

The network weights are generated by running train_3digit.py. Keep the resulting
multidigit_ctc.pth in the same directory as this file when deploying.
"""
from __future__ import annotations

from base64 import b64decode
from binascii import Error as Base64Error
from io import BytesIO
import logging
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
from flask import Flask, jsonify, request, send_from_directory
from PIL import Image, ImageOps, UnidentifiedImageError

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / "multidigit_ctc.pth"
BLANK_TOKEN = 10
NUM_CLASSES = 11
TARGET_DIGITS = 3
MAX_INPUT_WIDTH = 512
MEAN = 0.1307
STD = 0.3081

app = Flask(__name__)
app.config["MAX_CONTENT_LENGTH"] = 8 * 1024 * 1024


class MultiDigitCRNN(nn.Module):
    """CNN + bidirectional LSTM + CTC; must match train_3digit.py exactly."""

    def __init__(self) -> None:
        super().__init__()
        self.cnn = nn.Sequential(
            nn.Conv2d(1, 32, kernel_size=3, padding=1),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(kernel_size=2, stride=2),  # height/width / 2
            nn.Conv2d(32, 64, kernel_size=3, padding=1),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(kernel_size=2, stride=2),  # height/width / 4
            nn.Conv2d(64, 128, kernel_size=(3, 1), padding=(1, 0)),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(kernel_size=(2, 1)),
            nn.Conv2d(128, 128, kernel_size=(3, 1), padding=(1, 0)),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(kernel_size=(3, 1)),
        )
        self.rnn = nn.LSTM(
            input_size=128,
            hidden_size=128,
            num_layers=1,
            bidirectional=True,
            batch_first=True,
        )
        self.classifier = nn.Linear(256, NUM_CLASSES)

    def forward(self, images: torch.Tensor) -> torch.Tensor:
        features = self.cnn(images)  # [B, 128, 1, T]
        features = features.squeeze(2).transpose(1, 2)  # [B, T, 128]
        sequence, _ = self.rnn(features)
        return self.classifier(sequence).log_softmax(dim=-1).transpose(0, 1)  # [T,B,C]


def load_model() -> nn.Module:
    if not MODEL_PATH.is_file():
        raise FileNotFoundError(
            "multidigit_ctc.pth is missing. Run 'python train_3digit.py' first, "
            "then place the generated file beside app.py."
        )
    try:
        state = torch.load(MODEL_PATH, map_location="cpu", weights_only=True)
    except TypeError:  # compatibility with older supported PyTorch versions
        state = torch.load(MODEL_PATH, map_location="cpu")
    network = MultiDigitCRNN()
    network.load_state_dict(state, strict=True)
    network.eval()
    return network


model: nn.Module | None = None
model_error: str | None = None
try:
    model = load_model()
except Exception as exc:  # Keep the UI available so /api/health can explain the problem.
    model_error = str(exc)
    app.logger.warning("Model was not loaded: %s", model_error)


def prepare_number_image(image: Image.Image) -> torch.Tensor:
    """Convert the white canvas/black pen image into MNIST-style 28px input."""
    image = ImageOps.exif_transpose(image).convert("L")
    image.thumbnail((2400, 1200), Image.Resampling.LANCZOS)
    pixels = np.asarray(image)
    if pixels.size == 0 or pixels.ndim != 2:
        raise ValueError("The drawing is empty or invalid.")

    border = np.concatenate((pixels[0, :], pixels[-1, :], pixels[:, 0], pixels[:, -1]))
    # Browser canvas is white with dark ink; MNIST uses dark background/bright ink.
    if float(border.mean()) > 127:
        image = ImageOps.invert(image)
    image = ImageOps.autocontrast(image)
    pixels = np.asarray(image)
    ys, xs = np.where(pixels > 35)
    if xs.size == 0 or ys.size == 0:
        raise ValueError("No handwriting found. Draw all three digits before predicting.")

    top, bottom = int(ys.min()), int(ys.max()) + 1
    left, right = int(xs.min()), int(xs.max()) + 1
    height, width = pixels.shape
    ink_height = bottom - top
    # A little margin keeps the digit strokes from being cropped too tightly.
    pad_y = max(2, int(round(ink_height * 0.09)))
    pad_x = max(2, int(round(ink_height * 0.07)))
    top = max(0, top - pad_y)
    bottom = min(height, bottom + pad_y)
    left = max(0, left - pad_x)
    right = min(width, right + pad_x)

    crop = image.crop((left, top, right, bottom))
    target_height = 28
    scaled_width = max(1, int(round(crop.width * target_height / crop.height)))
    if scaled_width > MAX_INPUT_WIDTH:
        raise ValueError("Your drawing is too wide. Write three digits a little closer together.")

    resized = crop.resize((scaled_width, target_height), Image.Resampling.LANCZOS)
    array = np.asarray(resized, dtype=np.float32) / 255.0
    array = (array - MEAN) / STD
    tensor = torch.from_numpy(array).unsqueeze(0).unsqueeze(0)

    # Two horizontal pooling stages shrink width by a factor of four.
    width_now = tensor.shape[-1]
    padded_width = ((width_now + 3) // 4) * 4
    if padded_width != width_now:
        normalized_background = (0.0 - MEAN) / STD
        padded = torch.full(
            (1, 1, 28, padded_width), normalized_background, dtype=tensor.dtype
        )
        padded[:, :, :, :width_now] = tensor
        tensor = padded
    return tensor


def _logadd(a: float, b: float) -> float:
    return float(np.logaddexp(a, b))


def ctc_beam_decode_fixed_length(log_probs: torch.Tensor, target_length: int = TARGET_DIGITS,
                                 beam_width: int = 30) -> list[int]:
    """Prefix beam search restricted to exactly three output digits.

    The length constraint matches the application's stated task and prevents a
    greedy CTC path from returning only one or two characters. This cannot fix a
    poorly trained model, but it keeps the output sequence length consistent.
    """
    values = log_probs.detach().float().cpu().numpy()  # [T, classes], log probabilities
    # prefix -> (probability ending in blank, probability ending in non-blank)
    beam: dict[tuple[int, ...], tuple[float, float]] = {(): (0.0, -np.inf)}

    for timestep in range(values.shape[0]):
        probs = values[timestep]
        buckets: list[dict[tuple[int, ...], tuple[float, float]]] = [
            {} for _ in range(target_length + 1)
        ]

        def add(prefix: tuple[int, ...], blank_score: float | None = None,
                nonblank_score: float | None = None) -> None:
            bucket = buckets[len(prefix)]
            old_blank, old_nonblank = bucket.get(prefix, (-np.inf, -np.inf))
            if blank_score is not None:
                old_blank = _logadd(old_blank, blank_score)
            if nonblank_score is not None:
                old_nonblank = _logadd(old_nonblank, nonblank_score)
            bucket[prefix] = (old_blank, old_nonblank)

        for prefix, (p_blank, p_nonblank) in beam.items():
            total = _logadd(p_blank, p_nonblank)
            add(prefix, blank_score=total + float(probs[BLANK_TOKEN]))

            last_digit = prefix[-1] if prefix else None
            for digit in range(10):
                digit_score = float(probs[digit])
                if digit == last_digit:
                    # Same label without an intervening blank collapses to the same prefix.
                    add(prefix, nonblank_score=p_nonblank + digit_score)
                    # A repeated digit can extend only from a path that ended in blank.
                    if len(prefix) < target_length:
                        add(prefix + (digit,), nonblank_score=p_blank + digit_score)
                elif len(prefix) < target_length:
                    add(prefix + (digit,), nonblank_score=total + digit_score)

        # Keep a small beam for each prefix length. This prevents shorter strings
        # from eliminating all three-digit candidates before the final timestep.
        beam = {}
        for bucket in buckets:
            ranked = sorted(
                bucket.items(),
                key=lambda item: _logadd(item[1][0], item[1][1]),
                reverse=True,
            )[:beam_width]
            beam.update(ranked)

    candidates = [(prefix, _logadd(pair[0], pair[1]))
                  for prefix, pair in beam.items() if len(prefix) == target_length]
    if not candidates:
        raise ValueError("The model could not form a three-digit result. Please draw again.")
    best_prefix, _score = max(candidates, key=lambda item: item[1])
    return list(best_prefix)


@app.get("/")
def index():
    return send_from_directory(BASE_DIR, "index.html")


@app.get("/api/health")
def health():
    if model is None:
        return jsonify({
            "ok": False,
            "error": model_error or "The trained model is not loaded.",
            "next_step": "Run train_3digit.py and deploy multidigit_ctc.pth with app.py.",
        }), 503
    return jsonify({
        "ok": True,
        "model": "digitlab-exact-three-digit-ctc",
        "supports_exactly_three_digits": True,
    })


@app.post("/api/predict")
def predict():
    global model
    if model is None:
        return jsonify({
            "error": model_error or "The trained model is not loaded.",
            "next_step": "Run train_3digit.py and deploy multidigit_ctc.pth with app.py.",
        }), 503

    body = request.get_json(silent=True) or {}
    data_url = body.get("image", "")
    if not isinstance(data_url, str) or "," not in data_url:
        return jsonify({"error": "No drawing data was received. Draw three digits first."}), 400

    try:
        _header, encoded = data_url.split(",", 1)
        raw = b64decode(encoded, validate=True)
        with Image.open(BytesIO(raw)) as source:
            tensor = prepare_number_image(source)
        with torch.inference_mode():
            log_probs = model(tensor)[:, 0, :]
        digits = ctc_beam_decode_fixed_length(log_probs, TARGET_DIGITS)
        sequence = "".join(str(digit) for digit in digits)
        return jsonify({
            "sequence": sequence,
            "prediction": sequence,
            "digits": [
                {"position": index + 1, "prediction": digit}
                for index, digit in enumerate(digits)
            ],
            "digit_count": len(digits),
            "note": "The decoder is constrained to three digits; visual accuracy still depends on model training and handwriting clarity.",
        })
    except (ValueError, UnidentifiedImageError, Base64Error) as exc:
        return jsonify({"error": str(exc) or "Could not process the drawing."}), 400
    except Exception:
        app.logger.exception("Three-digit prediction failed")
        return jsonify({"error": "Could not process the drawing. Check the Render logs."}), 500


@app.errorhandler(413)
def request_too_large(_error):
    return jsonify({"error": "The drawing data is too large. Please draw the number again."}), 413


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=5000, debug=False)
